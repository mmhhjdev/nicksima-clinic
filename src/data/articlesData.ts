const getAssetPath = (imgPath: string) => {
  const cleanBase = import.meta.env.BASE_URL.endsWith('/') 
    ? import.meta.env.BASE_URL 
    : `${import.meta.env.BASE_URL}/`;
    
  const cleanPath = imgPath.startsWith('/') ? imgPath.slice(1) : imgPath;
  
  return `${cleanBase}${cleanPath}`;
};

